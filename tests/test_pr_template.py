def checked(body: str) -> list[str]:
    return [line for line in body.splitlines() if line.lstrip().startswith("- [x]")]


class TemplateDiscoveryTests(unittest.TestCase):
    """GitHub's template locations, case-insensitive, in GitHub's order."""

    def test_a_single_template_wins_in_githubs_order(self):
        self.assertEqual(choose_template(["README.md", ".github/pull_request_template.md"]),
                         (".github/pull_request_template.md", ""))
        self.assertEqual(choose_template(["docs/PULL_REQUEST_TEMPLATE.md",
                                          "PULL_REQUEST_TEMPLATE.md"]),
                         ("PULL_REQUEST_TEMPLATE.md", ""))
        self.assertEqual(choose_template(["docs/Pull_Request_Template.md"]),
                         ("docs/Pull_Request_Template.md", ""))
        self.assertEqual(choose_template(["src/pull_request_template.md"]), ("", ""))

    def test_a_template_directory_is_used_only_when_its_default_is_obvious(self):
        self.assertEqual(choose_template([".github/PULL_REQUEST_TEMPLATE/fix.md"]),
                         (".github/PULL_REQUEST_TEMPLATE/fix.md", ""))
        self.assertEqual(choose_template([".github/PULL_REQUEST_TEMPLATE/feature.md",
                                          ".github/PULL_REQUEST_TEMPLATE/default.md"]),
                         (".github/PULL_REQUEST_TEMPLATE/default.md", ""))
        path, note = choose_template([".github/PULL_REQUEST_TEMPLATE/feature.md",
                                      ".github/PULL_REQUEST_TEMPLATE/bug.md"])
        self.assertEqual(path, "")
        self.assertIn("2 templates", note)
        self.assertIn("plain description", note)

    def test_a_checkout_template_is_read_from_disk(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            self.assertFalse(template_in_checkout(root))
            (root / ".github").mkdir()
            (root / ".github" / "PULL_REQUEST_TEMPLATE.md").write_text("## Summary\n",
                                                                       encoding="utf-8")
            template = template_in_checkout(root)
            self.assertEqual(template.path, ".github/PULL_REQUEST_TEMPLATE.md")
            self.assertEqual(template.text, "## Summary\n")

    def test_a_github_template_is_read_through_the_contents_api(self):
        calls = []
        encoded = base64.b64encode(NOTALLYX_TEMPLATE.encode("utf-8")).decode("ascii")

        def get(url, params=None):
            calls.append((url, params))
            if url.endswith("/contents/.github"):
                return [{"name": "pull_request_template.md", "type": "file"},
                        {"name": "workflows", "type": "dir"}]
            if url.endswith("/contents/.github/pull_request_template.md"):
                return {"content": encoded}
            return []

        template = template_on_github(get, "https://api.github.com", "Crustack", "NotallyX",
                                      "main")
        self.assertEqual(template.path, ".github/pull_request_template.md")
        self.assertEqual(template.text, NOTALLYX_TEMPLATE)
        self.assertTrue(all(params == {"ref": "main"} for _, params in calls))


class TemplateFillingTests(unittest.TestCase):
    """NotallyX#1167 (2026-10-30): the body follows the repository's template,
    ticking only what the pipeline verified."""

    def facts(self, **overrides) -> TemplateFacts:
        facts = facts_from_pull_request(
            {"build_validation": {"status": "success", "task": ":app:testDebugUnitTest"}},
            NOTALLYX_DIFF)
        return TemplateFacts(**{**facts.__dict__, **overrides})

    def test_notallyx_template_is_filled_from_the_facts(self):
        body, notes = fill_template(NOTALLYX_TEMPLATE, DESCRIPTION, self.facts())
        self.assertEqual(notes, [])
        self.assertNotIn("<!--", body)
        self.assertNotIn("Fixes #", body)
        # Headings kept, in order, with the description under the first.
        headings = [line for line in body.splitlines() if line.startswith("## ")]
        self.assertEqual(headings, ["## Description", "## Related Issue", "## Type of Change",
                                    "## AI-Assisted Disclosure", "## Testing & Quality Checklist",
                                    "## Screenshots / Screen Recordings (if applicable)"])
        self.assertLess(body.index(DESCRIPTION), body.index("## Related Issue"))
        self.assertIn("## Related Issue\n\nNone.", body)
        self.assertEqual(checked(body), [
            "- [x] Bug fix (non-breaking change which fixes an issue)",
            "- [x] **AI-Assisted** (AI acted as a tool for boilerplate, autocomplete, or "
            "debugging, but a human authored/reviewed the logic and architecture).",
            "- [x] Code builds cleanly locally (`./gradlew assembleDebug` or similar). "
            "Ran `:app:testDebugUnitTest`.",
            "- [x] Added or updated unit/instrumented tests if applicable.",
            "- [x] No hardcoded secrets, API keys, or unintended debugging logs.",
        ])
        self.assertIn("- [ ] Tested on a device or emulator", body)
        self.assertTrue(body.rstrip().endswith("n/a"))
        # The publication text checks run on the filled body and pass.
        self.assertEqual(text_problems("Use SHA-256 for export hash verification", body), [])

    def test_unverified_facts_leave_their_boxes_unticked(self):
        body, _ = fill_template(NOTALLYX_TEMPLATE, DESCRIPTION, self.facts(
            build_status="failed", test_files=(),
            added_lines=('Log.d("x", "debug")', 'val apiKey = "abcd1234efgh"')))
        ticked = "\n".join(checked(body))
        self.assertNotIn("builds", ticked)
        self.assertNotIn("tests", ticked)
        self.assertNotIn("secrets", ticked)
        for status in ("success_app_module_only", "success_compile_only",
                       "success_on_analyzed_revision"):
            body, _ = fill_template(NOTALLYX_TEMPLATE, DESCRIPTION,
                                    self.facts(build_status=status))
            self.assertNotIn("builds", "\n".join(checked(body)), status)

    def test_device_testing_is_never_ticked_and_shipped_ticks_are_cleared(self):
        template = ("## Checklist\n- [x] I tested this on a physical device\n"
                    "- [X] I have read CONTRIBUTING.md\n- [ ] Tested on emulator API 34\n")
        body, _ = fill_template(template, DESCRIPTION, self.facts())
        self.assertEqual(checked(body), [])

    def test_ai_assisted_is_chosen_across_wordings(self):
        for options in (
            ["- [ ] No AI", "- [ ] AI assisted", "- [ ] AI generated"],
            ["- [ ] I did not use AI tools", "- [ ] I used AI tools to help write this code",
             "- [ ] The code was generated by AI"],
            ["- [ ] None", "- [ ] Partially (AI-aided review and autocomplete)",
             "- [ ] Fully generated by an LLM"],
        ):
            template = "## Use of AI\n" + "\n".join(options) + "\n"
            body, notes = fill_template(template, DESCRIPTION, self.facts())
            self.assertEqual(notes, [], options)
            self.assertEqual(checked(body), [options[1].replace("[ ]", "[x]")], options)
        self.assertTrue(is_assisted_option("AI-assisted (generated boilerplate only)"))
        self.assertFalse(is_assisted_option("**AI-Generated with Human Verification**"))

    def test_an_ai_question_without_an_assisted_option_is_left_to_the_operator(self):
        template = ("## AI disclosure\n- [ ] No AI was used\n- [ ] This PR contains "
                    "AI-generated code\n")
        body, notes = fill_template(template, DESCRIPTION, self.facts())
        self.assertEqual(checked(body), [])
        self.assertEqual(len(notes), 1)
        self.assertIn("no AI-assisted option", notes[0])

    def test_an_affirmation_box_is_left_unticked_with_its_own_note(self):
        """App Manager (2026-11-01): publishing would affirm that no AI was used."""
