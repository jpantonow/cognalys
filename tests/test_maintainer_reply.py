class MaintainerReplyTests(unittest.TestCase):
    """The comment posted after a revision answers the maintainer, briefly."""

    def test_a_short_plain_reply_is_kept(self):
        reply, issue = pr_feedback.maintainer_reply({
            "maintainer_reply": "Done: invalid values now show a \"Wrong numeric value\" toast "
                                "instead of being ignored; the text is in strings.xml."})
        self.assertTrue(reply.startswith("Done:"))
        self.assertEqual(issue, "")

    def test_long_structured_or_self_described_replies_are_refused(self):
        for text in ("x" * (pr_feedback.MAX_MAINTAINER_REPLY_CHARS + 1),
                     "## Summary\nChanged the handler.",
                     "Changes:\n- added a toast",
                     "This revision was generated by an LLM."):
            reply, issue = pr_feedback.maintainer_reply({"maintainer_reply": text})
            self.assertEqual(reply, "", text)
            self.assertIn("rejected", issue)
        self.assertEqual(pr_feedback.maintainer_reply({"maintainer_reply": ""}), ("", ""))

    def test_the_revision_schema_asks_for_the_reply(self):
        schema = pr_feedback.coordinated_pr_revision_schema()
        self.assertIn("maintainer_reply", schema["properties"])
        self.assertIn("maintainer_reply", schema["required"])
        system, _ = pr_feedback.coordinated_prompts({})
        self.assertIn("maintainer_reply", system)


class GovernedApiRemovalTests(unittest.TestCase):
    """jimvixx/ShortMessageSecure#83: asked to keep HmacSHA1, the revision swapped
    KeyGenerator for raw SecureRandom bytes the rule cannot see."""

    feedback = [{"kind": "comment", "body": "I'd prefer to preserve the existing "
                 "cryptographic behavior. Adding an explicit 160-bit initialization "
                 "to the current HmacSHA1 generator might be a simpler alternative."}]
    original = 'KeyGenerator generator = KeyGenerator.getInstance("HmacSHA256");'

    def test_dropping_the_governed_api_unasked_is_rejected(self):
        edits = [{"original_code": self.original,
                  "corrected_code": "byte[] s = new byte[20]; new SecureRandom().nextBytes(s);"}]
        issues = pr_feedback.governed_api_removal("KeyGeneratorSpec", edits, self.feedback, ["KeyGenerator"])
        self.assertEqual(len(issues), 1)
        self.assertIn("KeyGenerator", issues[0])

    def test_following_the_maintainers_suggestion_passes(self):
        edits = [{"original_code": self.original,
                  "corrected_code": 'KeyGenerator generator = KeyGenerator.getInstance("HmacSHA1");\n'
                                    "generator.init(160);"}]
        self.assertEqual(
            pr_feedback.governed_api_removal("KeyGeneratorSpec", edits, self.feedback, ["KeyGenerator"]), [])

    def test_the_governed_types_come_from_the_specification(self):
        import json
        import tempfile
        from pathlib import Path

        with tempfile.TemporaryDirectory() as directory:
            (Path(directory) / "AnyRule.json").write_text(json.dumps(
                {"applies_to_types": ["javax.crypto.KeyGenerator", "a.b.Widget"]}))
            self.assertEqual(pr_feedback.governed_types("AnyRule", Path(directory)),
                             ["KeyGenerator", "Widget"])
            # No specification, no assumption from the rule's name.
            self.assertEqual(pr_feedback.governed_types("KeyGeneratorSpec", Path(directory)), [])

    def test_a_maintainer_asking_to_drop_the_api_is_obeyed(self):
        edits = [{"original_code": self.original, "corrected_code": "byte[] s = random(20);"}]
        asked = [{"kind": "comment", "body": "Please drop KeyGenerator and use random bytes."}]
        self.assertEqual(pr_feedback.governed_api_removal("KeyGeneratorSpec", edits, asked, ["KeyGenerator"]), [])


if __name__ == "__main__":
    unittest.main()
